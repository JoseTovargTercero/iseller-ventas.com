/**
 * Reglas para sugerir una categoría de producto a partir de su nombre.
 * Devuelve el slug de categorias_producto; null si ninguna regla coincide.
 *
 * El orden importa: gana la primera regla que coincida, así que lo específico
 * va antes que lo genérico (p. ej. "PASTA DE TOMATE" antes que "PASTA").
 */
function cat_normalizar(string $nombre): string
{
    // Nombres guardados como UTF-8 leído como latin1 ("Ã‘" en lugar de "Ñ")
    $nombre = str_replace(["\xC3\x83\xC2\x91", "\xC3\x83\xE2\x80\x98"], 'N', $nombre);
    $nombre = str_replace("\xC3\x83", '', $nombre);
    $nombre = strtoupper($nombre);
    $nombre = strtr($nombre, [
        'Á' => 'A', 'É' => 'E', 'Í' => 'I', 'Ó' => 'O', 'Ú' => 'U', 'Ü' => 'U', 'Ñ' => 'N',
        'á' => 'A', 'é' => 'E', 'í' => 'I', 'ó' => 'O', 'ú' => 'U', 'ü' => 'U', 'ñ' => 'N',
        'À' => 'A', 'È' => 'E', 'Ì' => 'I', 'Ò' => 'O', 'Ù' => 'U', 'Â' => 'A', 'Ê' => 'E',
        'Ô' => 'O', 'Ã' => 'A', 'Õ' => 'O', 'Ç' => 'C',
    ]);
    $nombre = preg_replace('/[^A-Z0-9]+/', ' ', $nombre);
    return trim(preg_replace('/\s+/', ' ', $nombre));
}

function cat_sugerir(string $nombre): ?string
{
    $texto = ' ' . cat_normalizar($nombre) . ' ';
    foreach (CAT_REGLAS as [$slug, $patron]) {
        if (preg_match('/\b(?:' . $patron . ')\b/', $texto)) {
            return $slug;
        }
    }
    return null;
}

